// Server-side: maps a pipeline action to a concrete, whitelisted node command.
// The GUI can ONLY run these three scripts — the action is an enum, the script
// path is fixed, and args are derived from the queue, never from free text.
// Nothing here can execute an arbitrary command.

import { promises as fs } from 'fs'
import path from 'path'
import type { Prospect } from './queue'

const INGEST_DIR = path.join(process.cwd(), 'scripts', 'ingestion')
const CONFIG_PATH = path.join(INGEST_DIR, 'config.js')

export type RunAction = 'fetch' | 'extract' | 'import'

// source_type -> fetch-texts.mjs `source` value (see fetch-texts.mjs header).
const FETCH_SOURCE_MAP: Record<string, string> = {
  newadvent: 'newadvent',
  gutenberg: 'gutenberg',
  wikisource: 'wikisource',
  archive_online: 'generic',
}

// Which one-click actions apply to a given prospect.
export function availableActions(p: Prospect): RunAction[] {
  const actions: RunAction[] = []
  if (p.source_type && FETCH_SOURCE_MAP[p.source_type]) actions.push('fetch')
  if (p.source_type === 'gdrive_docx' && p.docx_path) actions.push('extract')
  return actions
}

export type Command = { cmd: string; args: string[]; cwd: string }

function esc(v: string | undefined): string {
  // Safe embedding of a string into the generated config.js module.
  return JSON.stringify(v ?? '')
}

// Generate scripts/ingestion/config.js from a prospect, for the `fetch` action.
async function writeFetchConfig(p: Prospect): Promise<void> {
  const source = FETCH_SOURCE_MAP[p.source_type ?? ''] ?? 'generic'
  const translationNotes =
    p.translator && p.translator_death_year
      ? `${p.translator} (d. ${p.translator_death_year}). Public-domain translation.`
      : ''
  const body = `// AUTO-GENERATED by the pipeline GUI from prospect "${p.id}".
// Edit and re-run manually if you need to adjust URLs or fields.

export default {
  collection: {
    name: ${esc(p.title)},
    slug: ${esc(p.collection_slug)},
    author: ${esc(p.author)},
    description: "",
  },
  urls: [${esc(p.source_url)}],
  source: ${esc(source)},
  knownFields: {
    genre: ${esc(p.genre)},
    sourceAttribution: "",
    provenanceNotes: ${esc(`Text sourced from ${p.source_type}. Accessed ${new Date().toISOString().slice(0, 7)}.`)},
    translationNotes: ${esc(translationNotes)},
    copyrightSafe: true,
  },
};
`
  await fs.writeFile(CONFIG_PATH, body, 'utf8')
}

// Build the command for an action, running any prep (e.g. writing config.js).
// Throws if the action isn't valid for this prospect.
export async function buildCommand(action: RunAction, prospect: Prospect): Promise<Command> {
  if (action === 'import') {
    return { cmd: 'node', args: [path.join(process.cwd(), 'scripts', 'pipeline-import.mjs')], cwd: process.cwd() }
  }

  if (action === 'fetch') {
    if (!availableActions(prospect).includes('fetch')) {
      throw new Error(`Prospect "${prospect.id}" (source ${prospect.source_type}) is not fetchable via fetch-texts.mjs.`)
    }
    if (!prospect.source_url) throw new Error(`Prospect "${prospect.id}" has no source_url.`)
    await writeFetchConfig(prospect)
    return { cmd: 'node', args: [path.join(INGEST_DIR, 'fetch-texts.mjs')], cwd: process.cwd() }
  }

  if (action === 'extract') {
    if (!prospect.docx_path) throw new Error(`Prospect "${prospect.id}" has no docx_path.`)
    if (!prospect.collection_slug) throw new Error(`Prospect "${prospect.id}" has no collection_slug for the output filename.`)
    return {
      cmd: 'node',
      args: [path.join(INGEST_DIR, 'extract-docx.mjs'), prospect.docx_path, `--slug=${prospect.collection_slug}`],
      cwd: process.cwd(),
    }
  }

  throw new Error(`Unknown action "${action}".`)
}

/**
 * queue.ts — the pure logic behind /admin/review.
 *
 * Everything here is a function over plain rows: no Supabase, no React, no
 * `next/*`. The review queue's judgement calls — is this provenance
 * self-consistent, does this author's tradition match their dates, where does
 * the operator resume — are exactly the parts that must not be wrong and are
 * also the parts that cannot be checked by loading the page (admin needs
 * Keith's own login; see CLAUDE.md). So they live here and are unit tested.
 */

export const REVIEW_PAGE_SIZE = 20

/**
 * The standalone group's stand-in slug in /admin/review/[slug].
 *
 * Safe as a sentinel because a real collection slug is generated by slugify()
 * and can never begin with an underscore.
 */
export const STANDALONE_SLUG = '_standalone'

export type ReviewState = 'pending' | 'approved' | 'held'

// ── Taxonomy warnings ────────────────────────────────────────────────────────

/**
 * Death-year ranges implied by a tradition, used to catch a mis-assigned
 * author before their work goes public.
 *
 * The bounds are deliberately loose and overlapping — Nicaea (325) is a
 * gradual boundary, not a cliff, and a figure who died in 330 is arguably
 * either. The check is meant to catch a 12th-century author filed under Early
 * Church, not to adjudicate the 330s.
 */
const TRADITION_DEATH_RANGES: Record<string, { min?: number; max?: number; label: string }> = {
  'early-church': { max: 340, label: 'Early Church' },
  patristic: { min: 325, max: 600, label: 'Patristic' },
}

export type TaxonomyInput = {
  authorName?: string | null
  traditionSlug?: string | null
  traditionName?: string | null
  deathYear?: number | null
  authorIsDraft?: boolean
  themeCount?: number
}

/**
 * Human-readable warnings for one text. Empty array means nothing to flag.
 * These are warnings, never blocks: the operator decides.
 */
export function taxonomyWarnings(input: TaxonomyInput): string[] {
  const warnings: string[] = []
  const who = input.authorName || 'This author'

  if (!input.traditionSlug) {
    warnings.push(`${who} has no tradition assigned.`)
  } else {
    const range = TRADITION_DEATH_RANGES[input.traditionSlug]
    const death = input.deathYear
    if (range && typeof death === 'number') {
      if (range.max !== undefined && death > range.max) {
        warnings.push(
          `${who} is filed under ${range.label} but died in ${death} — that tradition implies a death year of about ${range.max} or earlier.`
        )
      } else if (range.min !== undefined && death < range.min) {
        warnings.push(
          `${who} is filed under ${range.label} but died in ${death} — that tradition implies about ${range.min} or later.`
        )
      }
    }
  }

  if (typeof input.deathYear !== 'number') {
    warnings.push(`${who} has no death year recorded.`)
  }

  if (input.authorIsDraft) {
    warnings.push(
      `${who} is still a draft author — their page will have no bio and they stay off the Authors index until promoted.`
    )
  }

  if (input.themeCount === 0) {
    warnings.push('This text has no themes, so it will not appear on any theme page.')
  }

  return warnings
}

// ── Provenance ───────────────────────────────────────────────────────────────

export const PROVENANCE_FIELDS = [
  ['source_attribution', 'Source attribution'],
  ['provenance_notes', 'Provenance notes'],
  ['translation_notes', 'Translation notes'],
  ['source_url', 'Source URL'],
] as const

export type ProvenanceField = (typeof PROVENANCE_FIELDS)[number][0]

export type ProvenanceBearing = Record<ProvenanceField, string | null | undefined> & {
  title?: string
  slug?: string
}

export type ProvenanceSummary = {
  /** True when every text in the collection agrees on all four fields. */
  consistent: boolean
  /** The shared values, when consistent. */
  shared: Record<ProvenanceField, string | null>
  /** Fields that disagree, with the distinct values and which texts carry them. */
  conflicts: {
    field: ProvenanceField
    label: string
    values: { value: string | null; titles: string[] }[]
  }[]
}

/**
 * Compare the provenance of every text in a collection.
 *
 * A collection is supposed to come from one source, so a disagreement means
 * either a mixed import or a mistake — and it has to be shown loudly rather
 * than averaged into one card, because verifying the wrong provenance is how a
 * copyright problem ships.
 */
export function summariseProvenance(texts: ProvenanceBearing[]): ProvenanceSummary {
  const shared = {} as Record<ProvenanceField, string | null>
  const conflicts: ProvenanceSummary['conflicts'] = []

  for (const [field, label] of PROVENANCE_FIELDS) {
    const byValue = new Map<string, string[]>()
    for (const t of texts) {
      const key = normalise(t[field])
      if (!byValue.has(key)) byValue.set(key, [])
      byValue.get(key)!.push(t.title ?? t.slug ?? 'untitled')
    }

    if (byValue.size <= 1) {
      const only = [...byValue.keys()][0]
      shared[field] = only === '' ? null : only
      continue
    }

    shared[field] = null
    conflicts.push({
      field,
      label,
      values: [...byValue.entries()].map(([value, titles]) => ({
        value: value === '' ? null : value,
        titles,
      })),
    })
  }

  return { consistent: conflicts.length === 0, shared, conflicts }
}

function normalise(value: string | null | undefined): string {
  return (value ?? '').trim()
}

// ── Spot check ───────────────────────────────────────────────────────────────

/**
 * Two windows into the body: the opening, and a slice from the middle.
 *
 * The opening catches a bad import (a header block, a stray table of contents);
 * the middle catches OCR that degrades past the first page, which an opening-only
 * excerpt would never show. Both are cut at a word boundary so the sample never
 * ends mid-word and reads as damaged when it isn't.
 */
export function spotCheck(body: string | null | undefined, headChars = 600, midChars = 400): {
  head: string
  middle: string | null
} {
  const text = (body ?? '').trim()
  if (!text) return { head: '', middle: null }

  const head = cutAtWord(text.slice(0, headChars), text.length > headChars)

  // Only worth a second window if the middle isn't already inside the first.
  if (text.length <= headChars * 2) return { head, middle: null }

  const start = Math.floor(text.length / 2 - midChars / 2)
  const rawMiddle = text.slice(start, start + midChars)
  // Drop a leading partial word so the excerpt starts cleanly.
  const firstSpace = rawMiddle.indexOf(' ')
  const middle = cutAtWord(firstSpace > 0 ? rawMiddle.slice(firstSpace + 1) : rawMiddle, true)

  return { head, middle }
}

function cutAtWord(slice: string, truncated: boolean): string {
  if (!truncated) return slice.trim()
  const lastSpace = slice.lastIndexOf(' ')
  const cut = lastSpace > 0 ? slice.slice(0, lastSpace) : slice
  return `${cut.trim()}…`
}

// ── Resume ───────────────────────────────────────────────────────────────────

/**
 * Where to pick up: the first card not yet decided.
 *
 * Returns -1 when every text has been approved or held, which the caller shows
 * as "all reviewed" rather than scrolling to the top.
 */
export function firstPendingIndex(states: (ReviewState | null | undefined)[]): number {
  return states.findIndex(s => s == null || s === 'pending')
}

/** The 1-based page holding a given index, for the collection screen's paging. */
export function pageForIndex(index: number, pageSize = REVIEW_PAGE_SIZE): number {
  if (index < 0) return 1
  return Math.floor(index / pageSize) + 1
}

/** Clamp a user-supplied ?page= to something that exists. */
export function clampPage(raw: unknown, total: number, pageSize = REVIEW_PAGE_SIZE): number {
  const pages = Math.max(1, Math.ceil(total / pageSize))
  const parsed = typeof raw === 'string' ? parseInt(raw, 10) : typeof raw === 'number' ? raw : NaN
  if (!Number.isFinite(parsed) || parsed < 1) return 1
  return Math.min(Math.trunc(parsed), pages)
}

// ── Progress ─────────────────────────────────────────────────────────────────

export type Progress = { total: number; approved: number; held: number; pending: number }

export function progressOf(states: (ReviewState | null | undefined)[]): Progress {
  let approved = 0
  let held = 0
  for (const s of states) {
    if (s === 'approved') approved++
    else if (s === 'held') held++
  }
  return { total: states.length, approved, held, pending: states.length - approved - held }
}
